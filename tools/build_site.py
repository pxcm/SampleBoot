#!/usr/bin/env python3
"""Builds the one-page website in site/ (index.html is written by hand):

  site/assets/screen.js        the theme editor's renderer (a port of the C
                               drawing code), its font and the default theme,
                               so the demo screen matches the MPC
  site/assets/*.png|svg|jpg    logo, splash screens, a test image
  site/theme-editor.html       the theme editor, opened from the site

Run `make editor` first (the renderer is taken from tools/theme-editor.html).
"""
import json
import re
import shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = ROOT / "site"
ASSETS = SITE / "assets"
ASSETS.mkdir(parents=True, exist_ok=True)

editor = (ROOT / "tools" / "theme-editor.html").read_text()
js = editor[editor.index("<script>") + len("<script>"):]
js = js[:js.index("/* =====================================================================\n * Settings")]
js = js.replace('"use strict";', "")
# the test images, the splash screens and the original conf are not needed
js = "\n".join(l for l in js.split("\n")
               if not re.match(r"const (IMAGES|SPLASHES|ORIGINAL_CONF) = ", l))

# default theme from sampleboot.conf: colours as numbers, opacities as 0-100
theme = {}
for k, v in re.findall(r'^([A-Z_]+)=("?[^"\s]*"?)', (ROOT / "card" / "sampleboot.conf").read_text(), re.M):
    v = v.strip('"')
    if v.startswith("#"):
        theme[k] = int(v[1:], 16)
    elif k.endswith("_OPACITY"):
        theme[k] = int(v)

out = ("/* SampleBoot screen renderer for the website: generated by tools/build_site.py\n"
       " * from the theme editor, which ports src/sampleboot-ui.c line by line. */\n"
       "(function () {\n" + js +
       "\nconst THEME = " + json.dumps(theme) + ";\n"
       "window.SBScreen = { Screen, drawMenu, drawConfirm, drawMessage, drawStarting, drawSplash,\n"
       "  fitImage, to565, THEME, W, H, SPLASH_REVEAL, CONFIRM_S };\n"
       "})();\n")
(ASSETS / "screen.js").write_text(out)

for src, dst in [("card/splash-dark.png", "splash-dark.png"),
                 ("card/splash-light.png", "splash-light.png"),
                 ("docs/images/logo-dark.svg", "logo-dark.svg"),
                 ("docs/images/logo-light.svg", "logo-light.svg")]:
    shutil.copyfile(ROOT / src, ASSETS / dst)
shutil.copyfile(ROOT / "tools" / "theme-editor.html", SITE / "theme-editor.html")
print("site assets written:", ", ".join(sorted(p.name for p in ASSETS.iterdir())))
