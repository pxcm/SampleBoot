#!/usr/bin/env python3
"""Generates src/font_data.h: anti-aliased DejaVu Sans glyphs (8-bit alpha) for
code points 32-126 and 160-255 plus U+2026 (ellipsis), in a few sizes.
Run at development time only; the header is committed. Needs Pillow."""
import sys
from pathlib import Path
from PIL import ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONTS = ROOT / "fonts"
SIZES = [("FONT_SMALL", "DejaVuSans.ttf", 11), ("FONT_LABEL", "DejaVuSans-Bold.ttf", 13),
         ("FONT_NAME", "DejaVuSans-Bold.ttf", 17), ("FONT_BIG", "DejaVuSans-Bold.ttf", 28)]
CPS = list(range(32, 127)) + list(range(160, 256)) + [0x2026]

out = ["/* Generated by tools/gen_font.py from DejaVu Sans (see fonts/LICENSE-DejaVu.txt). */",
       "#pragma once", "#include <stdint.h>",
       "typedef struct { uint16_t cp; uint8_t adv, w, h; int8_t x, y; uint32_t off; } glyph_t;",
       "typedef struct { uint8_t ascent, height; uint16_t count; const glyph_t *g; const uint8_t *px; } font_t;"]
for name, file, size in SIZES:
    f = ImageFont.truetype(str(FONTS / file), size)
    asc, desc = f.getmetrics()
    glyphs, data = [], bytearray()
    for cp in CPS:
        ch = chr(cp)
        mask, (ox, oy) = f.getmask2(ch, mode="L", anchor="ls")
        w, h = mask.size
        adv = round(f.getlength(ch))
        glyphs.append((cp, adv, w, h, ox, oy, len(data)))
        data += bytes(mask)
    lo = name.lower()
    out.append(f"static const uint8_t {lo}_px[] = {{" + ",".join(str(b) for b in data) + (",0" if not data else "") + "};")
    out.append(f"static const glyph_t {lo}_g[] = {{" + ",".join(
        f"{{{cp},{adv},{w},{h},{ox},{oy},{off}}}" for cp, adv, w, h, ox, oy, off in glyphs) + "};")
    out.append(f"static const font_t {name} = {{{asc},{asc + desc},{len(glyphs)},{lo}_g,{lo}_px}};")
(ROOT / "src" / "font_data.h").write_text("\n".join(out) + "\n")
print("font_data.h written")
